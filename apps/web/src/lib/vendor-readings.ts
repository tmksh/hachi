const COMPOUND_MAP = new Map(COMPOUNDS);
const COMPOUND_LENS = [...new Set(COMPOUNDS.map(([k]) => k.length))].sort((a, b) => b - a);

function isKanaOrLatin(ch: string): boolean {
  return /[ぁ-んァ-ンーa-z0-9]/i.test(ch);
}

/** 漢字を含む業者名をひらがな読みにする。未知の漢字はそのまま残す。 */
export function kanjiToHiraganaReading(text: string): string {
  let i = 0;
  let out = "";
  while (i < text.length) {
    let hit = "";
    let hitLen = 0;
    for (const len of COMPOUND_LENS) {
      const slice = text.slice(i, i + len);
      const reading = COMPOUND_MAP.get(slice);
      if (reading) {
        hit = reading;
        hitLen = len;
        break;
      }
    }
    if (hitLen) {
      out += hit;
      i += hitLen;
      continue;
    }
    const ch = text[i];
    if (SINGLE[ch]) out += SINGLE[ch];
    else if (isKanaOrLatin(ch) || ch === "ー") out += ch;
    i += 1;
  }
  return out;
}
